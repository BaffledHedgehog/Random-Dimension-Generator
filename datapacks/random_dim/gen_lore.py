def generate_lore_40_words(rng):
    """Generate surreal atmospheric lore text of ~40 words (reduced 2.5x from 100 words)."""
    intro = rng.choice(_FRAGMENTS_INTRO)
    mid = rng.choice(_FRAGMENTS_MID)
    end = rng.choice(_FRAGMENTS_END)
    text = f"{intro}, {mid} {end}"
    return text


def generate_50_book_pages(rng, component_form=False):
    """Generate 50 pages of atmospheric procedural text for writable or written book items.
    
    component_form=False -> raw strings for writable_book.
    component_form=True  -> text components with styling for written_book.
    """
    colors = ["dark_purple", "gold", "dark_aqua", "blue", "dark_green", "dark_red", "light_purple"]
    pages = []
    for _ in range(50):
        text = generate_lore_40_words(rng)
        if component_form:
            raw = {
                "text": text,
                "color": rng.choice(colors),
                "italic": True,
            }
            if rng.random() < 0.15:
                raw["bold"] = True
        else:
            raw = text
        p = {"raw": raw}
        if rng.random() < 0.10:
            p["filtered"] = "..." if not component_form else {"text": "..."}
        pages.append(p)
    return pages
